export function seekerToDeckCard(seeker: SeekerProfile): DeckCard {
  return {
    id: seeker.id,
    kind: 'seeker',
    name: seeker.name,
    age: seeker.age,
    headline: seeker.title,
    subline: `${seeker.location} · ${seeker.distanceMi} mi`,
    tag: seeker.workMode,
    badge: 'Open to work',
    tagsLabel: 'Skills',
    tags: seeker.skills,
    mutualConnections: seeker.mutualConnections,
    meta: seeker.responseTime,
    metaSecondary: `${seeker.yearsExperience} yrs experience`,
    verified: seeker.verified,
    isNew: seeker.isNew,
    activeNow: seeker.activeNow,
    featured: seeker.featured,
    matchScore: seeker.matchScore,
    willMatchBack: seeker.willMatchBack,
    avatarColor: seeker.avatarColor,
    photoUrl: seeker.photoUrl,
    prompts: seeker.prompts,
  };
}
