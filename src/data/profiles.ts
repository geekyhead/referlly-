export function profileToDeckCard(profile: Profile): DeckCard {
  return {
    id: profile.id,
    kind: 'recruiter',
    name: profile.name,
    age: profile.age,
    headline: profile.role,
    subline: `${profile.company} · ${profile.distanceMi} mi`,
    tag: profile.companyTag,
    badge: profile.openToRefer ? 'Open to refer' : undefined,
    tagsLabel: 'Hiring for',
    tags: profile.hiringFor,
    mutualConnections: profile.mutualConnections,
    meta: profile.responseTime,
    metaSecondary: `${profile.yearsAtCompany} yrs at company`,
    verified: profile.verified,
    isNew: profile.isNew,
    activeNow: profile.activeNow,
    featured: profile.featured,
    matchScore: profile.matchScore,
    willMatchBack: profile.willMatchBack,
    avatarColor: profile.avatarColor,
    photoUrl: profile.photoUrl,
    prompts: profile.prompts,
  };
}
